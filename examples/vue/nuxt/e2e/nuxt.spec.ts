test('native deep links, browser history, document title and 390px layout work', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await page.setViewportSize({ width: 390, height: 844 })
  const noOverflow = async () => expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)

  await page.goto('/')
  await expect(page).toHaveTitle('Главная - FEOD Shop')
  await expect(page.getByRole('heading', { level: 1, name: 'Добро пожаловать в FEOD Shop' })).toBeVisible()
  await noOverflow()
  await page.getByRole('link', { name: 'Каталог', exact: true }).click()
  await expect(page).toHaveURL(/\/catalog$/)
  await expect(page).toHaveTitle('Каталог - FEOD Shop')
  await noOverflow()
  await page.getByRole('link', { name: 'О проекте', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'О FEOD Shop' })).toBeVisible()
  await expect(page).toHaveTitle('О FEOD Shop - FEOD Shop')
  await page.goBack()
  await expect(page).toHaveURL(/\/catalog$/)
  await page.goForward()
  await expect(page).toHaveURL(/\/about$/)
  await noOverflow()

  const missing = await page.request.get('/route-does-not-exist')
  expect(missing.status()).toBe(404)
  expect(pageErrors).toEqual([])
})

test('product route fetches data from Nitro and returns 404 for unknown ids', async ({ page, request }) => {
  const api = await request.get('/api/products/2')
  expect(api.ok()).toBeTruthy()
  expect((await api.json()).title).toBe('Продукт 2')
  expect((await request.get('/api/products/999')).status()).toBe(404)

  const html = await (await request.get('/catalog/2')).text()
  expect(html).toContain('<title>Продукт 2 - FEOD Shop</title>')
  expect(html).toContain('Описание продукта 2')
  expect((await request.get('/catalog/999')).status()).toBe(404)

  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await page.goto('/catalog')
  await page.getByRole('link', { name: 'Продукт 2', exact: true }).click()
  await expect(page).toHaveURL(/\/catalog\/2$/)
  await expect(page).toHaveTitle('Продукт 2 - FEOD Shop')
  await page.getByRole('button', { name: 'В корзину', exact: true }).click()
  await expect(page.getByRole('button', { name: 'В корзине', exact: true })).toBeDisabled()
  await expect(page.getByRole('link', { name: 'Открыть корзину' })).toContainText('2000 ₽')
  await page.getByRole('link', { name: '← Вернуться в каталог' }).click()
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Продукт 2', exact: true }) })
  await expect(card.getByRole('button', { name: 'В корзине', exact: true })).toBeDisabled()
  await page.goto('/catalog/999')
  await expect(page.getByRole('heading', { name: 'Страница не найдена' })).toBeVisible()
  await expect(page.getByText('Товар не найден')).toBeVisible()
  await expect(page).toHaveTitle('Страница не найдена - FEOD Shop')
  expect(pageErrors).toEqual([])
})
