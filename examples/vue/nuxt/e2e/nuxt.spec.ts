import { expect, test } from '@playwright/test'

test('server renders route metadata and fresh requests receive isolated Pinia state', async ({ page, request }) => {
  const response = await request.get('/catalog')
  expect(response.ok()).toBeTruthy()
  const html = await response.text()
  expect(html).toContain('Каталог продуктов')
  expect(html).toContain('<title>Каталог - FEOD Shop</title>')
  expect(html).toContain('Продукт 1')

  await page.goto('/profile')
  await page.getByRole('button', { name: 'Редактировать', exact: true }).click()
  await page.getByLabel('Имя', { exact: true }).fill('Только в этом браузере')
  await page.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(page.locator('.user-widget__name')).toHaveText('Только в этом браузере')

  const isolated = await page.context().browser()?.newContext()
  expect(isolated).toBeTruthy()
  const secondPage = await isolated!.newPage()
  await secondPage.goto('http://127.0.0.1:4180/profile')
  await expect(secondPage.locator('.user-widget__name')).toHaveText('Иван Иванов')
  await isolated!.close()
})

test('catalog and cart mutations update totals, quantity, removal and widget', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await page.goto('/catalog')
  await expect(page.getByRole('heading', { level: 1, name: 'Каталог продуктов' })).toBeVisible()

  const product = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Продукт 1', exact: true }) })
  await product.getByRole('button', { name: 'В корзину', exact: true }).click()
  const secondProduct = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Продукт 2', exact: true }) })
  await secondProduct.getByRole('button', { name: 'В корзину', exact: true }).click()
  const cartWidget = page.getByRole('link', { name: 'Открыть корзину' })
  await expect(cartWidget).toContainText('3000 ₽')
  await expect(page.locator('.cart-widget__counter')).toHaveText('2')
  await cartWidget.click()
  const item = page.getByRole('listitem').filter({ has: page.getByRole('heading', { name: 'Продукт 1', exact: true }) })
  await expect(page.locator('.cart-summary__total')).toContainText('3000 ₽')
  await item.getByRole('button', { name: 'Увеличить количество: Продукт 1' }).click()
  await expect(page.locator('.cart-summary__total')).toContainText('4000 ₽')
  await expect(page.locator('.cart-widget__counter')).toHaveText('3')
  await item.getByRole('button', { name: 'Уменьшить количество: Продукт 1' }).click()
  await expect(page.locator('.cart-summary__total')).toContainText('3000 ₽')
  await item.getByRole('button', { name: 'Удалить товар: Продукт 1' }).click()
  await expect(page.locator('.cart-summary__total')).toContainText('2000 ₽')
  await expect(page.locator('.cart-widget__counter')).toHaveText('1')
  await page.getByRole('button', { name: 'Оформить заказ' }).click()
  await expect(page.getByText('Ваша корзина пуста', { exact: true })).toBeVisible()
  await expect(page.locator('.cart-widget__counter')).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Открыть корзину' })).not.toContainText('2000 ₽')
  expect(pageErrors).toEqual([])
})

