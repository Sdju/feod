import { expect, test } from '@playwright/test'

test('catalog, cart, quantity controls, and clear action work together', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1, name: 'Добро пожаловать в FEOD Shop' })).toBeVisible()
  await page.getByRole('link', { name: 'Каталог', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Каталог продуктов' })).toBeVisible()
  const product = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Продукт 1', exact: true }) })
  await product.getByRole('button', { name: 'В корзину' }).click()
  await expect(product.getByRole('button', { name: 'В корзине' })).toBeDisabled()
  await expect(page.getByRole('link', { name: 'Открыть корзину' })).toContainText('1000 ₽')
  await expect(page.locator('.cart-widget__counter')).toHaveText('1')
  await page.getByRole('link', { name: 'Открыть корзину' }).click()
  const item = page.getByRole('listitem').filter({ has: page.getByRole('heading', { name: 'Продукт 1', exact: true }) })
  await expect(page.locator('.cart-summary__total')).toContainText('1000 ₽')
  await item.getByRole('button', { name: 'Увеличить количество Продукт 1' }).click()
  await expect(page.locator('.cart-summary__total')).toContainText('2000 ₽')
  await expect(page.locator('.cart-widget__counter')).toHaveText('2')
  await item.getByRole('button', { name: 'Уменьшить количество Продукт 1' }).click()
  await expect(page.locator('.cart-summary__total')).toContainText('1000 ₽')
  await expect(page.locator('.cart-widget__counter')).toHaveText('1')
  await item.getByRole('button', { name: 'Удалить' }).click()
  await expect(page.getByText('Ваша корзина пуста')).toBeVisible()
  await expect(page.locator('.cart-widget__counter')).toHaveCount(0)
  await page.getByRole('link', { name: 'Каталог', exact: true }).click()
  const secondProduct = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Продукт 1', exact: true }) })
  await secondProduct.getByRole('button', { name: 'В корзину' }).click()
  await expect(page.locator('.cart-widget__counter')).toHaveText('1')
  await page.getByRole('link', { name: 'Открыть корзину' }).click()
  await page.getByRole('button', { name: 'Оформить заказ' }).click()
  await expect(page.getByText('Ваша корзина пуста')).toBeVisible()
  await expect(page.locator('.cart-widget__counter')).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Открыть корзину' })).not.toContainText('1000 ₽')
  expect(errors).toEqual([])
})

test('profile labels, save, cancel, and shared widget state', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/profile')
  await page.getByRole('button', { name: 'Редактировать' }).click()
  await page.getByLabel('Имя', { exact: true }).fill('Анна Петрова')
  await page.getByLabel('Email', { exact: true }).fill('anna@example.com')
  await page.getByLabel('Телефон', { exact: true }).fill('+7 900 000-00-00')
  await page.getByLabel('Адрес', { exact: true }).fill('Санкт-Петербург')
  await page.getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.locator('.user-profile__info')).toContainText('Анна Петрова')
  await expect(page.getByRole('link', { name: /Анна Петрова/ })).toBeVisible()
  await page.getByRole('button', { name: 'Редактировать' }).click()
  await page.getByLabel('Имя', { exact: true }).fill('Не сохранено')
  await page.getByRole('button', { name: 'Отмена' }).click()
  await expect(page.getByRole('link', { name: /Анна Петрова/ })).toBeVisible()
  await page.getByRole('button', { name: 'Редактировать' }).click()
  await expect(page.getByLabel('Имя', { exact: true })).toHaveValue('Анна Петрова')
  expect(errors).toEqual([])
})

test('mobile routes work at 390px without horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const noOverflow = async () => expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.goto('/')
  await noOverflow()
  await page.getByRole('link', { name: 'Каталог', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Каталог продуктов' })).toBeVisible()
  await noOverflow()
  const product = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Продукт 1', exact: true }) })
  await product.getByRole('button', { name: 'В корзину' }).click()
  await page.getByRole('link', { name: 'Открыть корзину' }).click()
  await noOverflow()
  await page.getByRole('link', { name: /Иван Иванов/ }).click()
  await expect(page.getByRole('heading', { name: 'Профиль' })).toBeVisible()
  await noOverflow()
  await page.getByRole('link', { name: 'О проекте', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'О FEOD Shop' })).toBeVisible()
  await noOverflow()
})

test('deep links, titles, browser history, and unknown routes', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/catalog')
  await expect(page).toHaveTitle('Каталог - FEOD Shop')
  await expect(page.getByRole('heading', { name: 'Каталог продуктов' })).toBeVisible()
  await page.getByRole('link', { name: 'Открыть корзину' }).click()
  await expect(page).toHaveTitle('Корзина - FEOD Shop')
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'Каталог продуктов' })).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('heading', { name: 'Корзина' })).toBeVisible()
  await page.goto('/about')
  await expect(page).toHaveTitle('О проекте - FEOD Shop')
  await page.goto('/missing')
  await expect(page.getByRole('heading', { name: 'Страница не найдена' })).toBeVisible()
  expect(errors).toEqual([])
})
